export const RULES_TEXT = `ラインクラフト（Line Craft） ルール

■ コンセプト
場に並ぶ3枚のタイルから1枚を選び、盤上4x4マスの好きな場所に置く。
縦・横・斜め、合計10本のラインで相手より合計値が大きいラインを多く作った方が勝ち。

■ ターンの流れ
1. ドラフト: マーケット（最大3枚）から1枚選んで手に取る
2. 配置: 盤面の空いているマスに置く（一度置いたら動かせない）
3. 補充: 山札の一番上をマーケットに補充する（山札切れなら補充なし）
4. 手番交代（順番は下記スネークドラフトを参照）

■ 手番順（スネークドラフト）
P1, P2, P2, P1 の4手を1ブロックとして繰り返す。
これにより「毎回先に選べる」有利さを緩和している。

■ 終了条件
16マスすべてが埋まったら終了。必ずちょうど16手（各8手）で終わる。

■ 得点計算
各ライン（4マス）で自分の置いた数字の合計が相手より大きければ1点。
同点ならそのラインは引き分け（無得点）。
ライン得点が多い方が勝ち。同点なら盤面全体の合計値で判定、それも同じなら引き分け。

■ 運と戦略
山札の並びには乱数要素があるが、マーケットは常に見えているので
「引いた運」より「選ぶ判断」の比重が大きいゲームです。
`
